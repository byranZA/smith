// TestConvergeRefusesAVariableWithNoStagedValue proves a variable the staged
// blueprint declares but has no staged value for fails the step by name,
// rather than reading the box's own environment or exporting the reference as
// though it were a token.
func TestConvergeRefusesAVariableWithNoStagedValue(t *testing.T) {
	home := t.TempDir()
	box := &fakeBox{installed: map[string]bool{}, hasMise: true}
	b := blueprint.Blueprint{Env: map[string]string{"GITHUB_TOKEN": "env:GITHUB_TOKEN"}}
	t.Setenv("GITHUB_TOKEN", "ghp_fromtheboxenv")

	var progress bytes.Buffer
	env := Env{Command: box, StateRoot: t.TempDir()}
	result, err := Converge(context.Background(), env, Plan(b, home), &progress)
	if err != nil {
		t.Fatalf("Converge() error = %v, want nil", err)
	}

	if !result.Failed() {
		t.Fatalf("Result.Failed() = false, want true: %s", result.Report())
	}
	if err := result.Outcomes[0].Err; err == nil || !strings.Contains(err.Error(), "GITHUB_TOKEN") {
		t.Errorf("outcome error = %v, want it to name the variable with no staged value", err)
	}
	if _, err := os.Stat(fragmentPath(home)); !os.IsNotExist(err) {
		t.Errorf("a fragment was written for a blueprint whose value was never staged")
	}
}

// TestConvergeNeverTouchesTheOperatorsOwnMiseConfig proves the file mise calls
// its own is neither read nor written: it is where the operator's settings
// live, and it outranks smith's fragment on purpose.
func TestConvergeNeverTouchesTheOperatorsOwnMiseConfig(t *testing.T) {
	home := t.TempDir()
	own := filepath.Join(home, ".config", "mise", "config.toml")
	if err := os.MkdirAll(filepath.Dir(own), 0o700); err != nil {
		t.Fatalf("make the operator's mise config directory: %v", err)
	}
	if err := os.WriteFile(own, []byte("[tools]\nnode = \"18\"\n"), 0o600); err != nil {
		t.Fatalf("write the operator's mise config: %v", err)
	}
	before := modTime(t, own)
	box := &fakeBox{installed: map[string]bool{}, hasMise: true}

	convergeOnBox(t, box, home, blueprint.Blueprint{Tools: map[string]string{"node": "20"}})

	if got := held(t, own); got != "[tools]\nnode = \"18\"\n" {
		t.Errorf("the operator's own mise config = %q, want it unchanged", got)
	}
	if after := modTime(t, own); !after.Equal(before) {
		t.Errorf("the operator's own mise config was rewritten at %v, want it untouched", after)
	}
	if box.ran("use") {
		t.Errorf("the stage ran %v, want no mise use — it would write the operator's own config", box.calls)
	}
	if box.ran("activate") {
		t.Errorf("the stage ran %v, want no mise activate — it does not fire in the shells smith runs in", box.calls)
	}
}

