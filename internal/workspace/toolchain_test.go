// TestConvergeInstallsMiseWhenTheBoxLacksIt proves a box with no mise gets one,
// and that what the stage runs afterwards is the binary it just installed.
func TestConvergeInstallsMiseWhenTheBoxLacksIt(t *testing.T) {
	home := t.TempDir()
	box := &fakeBox{installed: map[string]bool{}}
	b := blueprint.Blueprint{Tools: map[string]string{"node": "20"}}

	result, progress := convergeOnBox(t, box, home, b)

	if result.Failed() {
		t.Fatalf("Result.Failed() = true, want false: %s", result.Report())
	}
	if !box.ran("mise.run") {
		t.Errorf("the stage ran %v, want it to install mise on a box that has none", box.calls)
	}
	if want := filepath.Join(home, ".local", "bin", "mise"); box.miseAt != want {
		t.Errorf("mise is invocable at %q after the stage installed it, want %q", box.miseAt, want)
	}
	if !strings.Contains(progress, "mise") {
		t.Errorf("progress = %q, want the toolchain step reported as it completes", progress)
	}
}

