// modTime is when the box last wrote path, and fails the test when the box
// holds nothing there.
func modTime(t *testing.T, path string) time.Time {
	t.Helper()
	info, err := os.Stat(path)
	if err != nil {
		t.Fatalf("read the modification time of %s: %v", path, err)
	}
	return info.ModTime()
}

