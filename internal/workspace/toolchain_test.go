// TestPlanToolchain drives the pure derivation of the toolchain unit: what the
// blueprint has to declare for the box to get one, and what the unit carries.
func TestPlanToolchain(t *testing.T) {
	tests := []struct {
		name string
		b    blueprint.Blueprint
		want []Fragment
	}{
		{
			name: "declared tools are pinned in the smith-owned fragment",
			b:    blueprint.Blueprint{Tools: map[string]string{"node": "20", "go": "1.23"}},
			want: []Fragment{{
				Path:  "/home/smith/.config/mise/conf.d/smith.toml",
				Mise:  "/home/smith/.local/bin/mise",
				Tools: map[string]string{"node": "20", "go": "1.23"},
			}},
		},
		{
			name: "declared env alone still plans the fragment that exports it",
			b:    blueprint.Blueprint{Env: map[string]string{"GITHUB_TOKEN": "env:GITHUB_TOKEN"}},
			want: []Fragment{{
				Path: "/home/smith/.config/mise/conf.d/smith.toml",
				Mise: "/home/smith/.local/bin/mise",
				Env:  []string{"GITHUB_TOKEN"},
			}},
		},
		{
			name: "a repo alone plans the toolchain, because a clone runs under mise",
			b:    blueprint.Blueprint{Repos: []blueprint.Repo{{Name: "acme", URL: "git@example.com:acme.git"}}},
			want: []Fragment{{
				Path: "/home/smith/.config/mise/conf.d/smith.toml",
				Mise: "/home/smith/.local/bin/mise",
			}},
		},
		{
			name: "a blueprint with no toolchain and no repo plans none",
			b:    blueprint.Blueprint{Packages: []string{"ripgrep"}},
			want: nil,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var got []Fragment
			for _, unit := range Plan(tt.b, "/home/smith") {
				if unit.Step == Toolchain {
					got = append(got, unit.Fragment)
				}
			}
			if len(got) != len(tt.want) {
				t.Fatalf("Plan() planned %d toolchain units, want %d: %+v", len(got), len(tt.want), got)
			}
			for i, tc := range got {
				if tc.Path != tt.want[i].Path || tc.Mise != tt.want[i].Mise {
					t.Errorf("Plan() toolchain %d paths = %q, %q, want %q, %q", i, tc.Path, tc.Mise, tt.want[i].Path, tt.want[i].Mise)
				}
				if !maps.Equal(tc.Tools, tt.want[i].Tools) {
					t.Errorf("Plan() toolchain %d tools = %v, want %v", i, tc.Tools, tt.want[i].Tools)
				}
				if !slices.Equal(tc.Env, tt.want[i].Env) {
					t.Errorf("Plan() toolchain %d env = %v, want %v", i, tc.Env, tt.want[i].Env)
				}
			}
		})
	}
}

// TestPlanToolchainIsPure proves a caller that mutates a planned unit cannot
// reach back into the blueprint it was planned from.
func TestPlanToolchainIsPure(t *testing.T) {
	b := blueprint.Blueprint{Tools: map[string]string{"node": "20"}}
	for _, unit := range Plan(b, "/home/smith") {
		if unit.Step == Toolchain {
			unit.Fragment.Tools["node"] = "22"
		}
	}
	if b.Tools["node"] != "20" {
		t.Errorf("blueprint tools = %v after a caller mutated the plan, want node 20", b.Tools)
	}
}

// TestGenerate pins the bytes of the generated fragment against the golden
