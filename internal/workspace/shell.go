// SessionMise is the mise executable a session on this box runs its process
// under, with home the smith user's home: the binary the toolchain step
// installed there when it is an executable file, else mise by name on PATH.
func SessionMise(home string) string {
	installed := filepath.Join(home, miseDir, miseFile)
	if info, err := os.Stat(installed); err == nil && info.Mode().IsRegular() && info.Mode().Perm()&0o111 != 0 {
		return installed
	}
	return miseFile
}

// defaultProfile is where the login profile lands on a real box. Every login
// shell sources /etc/profile.d, even one whose ~/.bash_profile stops
// ~/.profile being read, and the operator's own dotfiles stay untouched.
const defaultProfile = "/etc/profile.d/smith.sh"

// profileMode is the login profile's permissions: every login shell reads it,
// and it holds no secret.
const profileMode = "0644"

// profile is the login profile smith owns whole. It puts mise's shims on PATH
// ahead of the system directories when they exist, so a half-set-up box still
// logs in, and exports no env: a shim runs its tool with the declared env in
// scope.
const profile = `# Generated by smith — do not edit.
#
# ` + "`smith workspace converge`" + ` writes this file whole, so anything added here
# is lost on the next run. It puts mise's shims on PATH ahead of the system
# directories, so the tools the box's blueprint declares answer by name in a
# login shell. It exports none of the blueprint's env: a shim runs its tool
# with that env in scope.
smith_shims="$HOME/.local/share/mise/shims"
if [ -d "$smith_shims" ]; then
	smith_path=":$PATH:"
	while :; do
		case "$smith_path" in
		*":$smith_shims:"*) smith_path="${smith_path%%:"$smith_shims":*}:${smith_path#*:"$smith_shims":}" ;;
		*) break ;;
		esac
	done
	smith_path="${smith_path#:}"
	smith_path="${smith_path%:}"
	PATH="$smith_shims${smith_path:+:$smith_path}"; export PATH
	unset smith_path
fi
unset smith_shims
`

// writeProfile puts the login profile at path and reports what it did to the
// file. It is check-before-change, like the fragment, and writes through sudo
// because the profile directory belongs to root.
func writeProfile(ctx context.Context, run Runner, path string, progress io.Writer) (string, error) {
	current, exists, err := onBox(path)
	if err != nil {
		return "", err
	}
	if exists && string(current) == profile {
		return "unchanged " + path, nil
	}
	args := []string{"install", "-D", "-m", profileMode, "/dev/stdin", path}
	if err := run.Run(ctx, "sudo", args, strings.NewReader(profile), progress, progress); err != nil {
		return "", fmt.Errorf("write the login profile %s: %w", path, err)
	}
	if exists {
		return "rewrote " + path, nil
	}
	return "wrote " + path, nil
}
